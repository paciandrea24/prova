function initializeRacingGame(lobbyId, players, settings) {
    console.log(`🏎️ Inizializzazione Campionato per lobby ${lobbyId}`);

    // 1. Quante mappe ha scelto l'host? (Se non c'è il dato, usa 3 di default)
    const requestedTracks = settings.numTracks || 3;

    // 2. Mescoliamo a caso tutte le mappe disponibili nel gioco
    // Usa lo spread operator [...] per non modificare l'array originale TRACKS
    let shuffledTracks = [...TRACKS].sort(() => Math.random() - 0.5);

    // 3. Tagliamo l'array per prendere SOLO il numero di mappe richieste!
    // (Se chiedi 5 mappe ma ne hai create solo 3, slice prende automaticamente il massimo disponibile)
    let selectedTracks = shuffledTracks.slice(0, requestedTracks);

    const game = {
        lobbyId,
        gameId: 'racing',
        players: [...players],
        playersState: {},

        // Assegniamo SOLO le mappe selezionate e mescolate
        tracks: selectedTracks,
        currentTrackIndex: 0,
        cumulativeTimes: {},

        tileSize: TILE_SIZE,
        podium: [],
        isActive: false,
        startTime: null,
        loopInterval: null
    };

    // Inizializza i tempi cumulativi a zero per tutti
    players.forEach(p => {
        game.cumulativeTimes[p] = 0;
    });

    // Posiziona i giocatori sulla prima mappa estratta
    resetPlayersForCurrentTrack(game);

    activeGames.set(lobbyId, game);
    return game;
}

// Funzione helper per riposizionare le auto ad ogni nuova gara
function resetPlayersForCurrentTrack(game) {
    const track = game.tracks[game.currentTrackIndex];
    game.podium = []; // Svuota il podio della singola gara

    game.players.forEach(p => {
        game.playersState[p] = {
            color: p,
            x: track.spawnX,
            y: track.spawnY,
            angle: track.angle,
            inputs: { w: false, a: false, s: false, d: false },
            progress: 0,
            finished: false,
            place: null,
            time: null
        };
    });
}

function runGameLoop(io, lobbyId) {
    const game = activeGames.get(lobbyId);
    if (!game) return;

    const speed = 18;
    const carWidth = 86;
    const carHeight = 40;
    const currentTrackMap = game.tracks[game.currentTrackIndex].map;

    game.loopInterval = setInterval(() => {
        if (!game.isActive) return;

        let everyoneFinished = true;

        for (const [color, pState] of Object.entries(game.playersState)) {
            if (pState.finished) continue;
            everyoneFinished = false;

            let dx = 0;
            let dy = 0;

            if (pState.inputs.w) dy -= speed;
            if (pState.inputs.s) dy += speed;
            if (pState.inputs.a) dx -= speed;
            if (pState.inputs.d) dx += speed;

            let nextX = pState.x + dx;
            let nextY = pState.y + dy;

            let points = [
                { x: nextX, y: nextY },
                { x: nextX + carWidth, y: nextY },
                { x: nextX, y: nextY + carHeight },
                { x: nextX + carWidth, y: nextY + carHeight }
            ];

            let canMove = true;
            let hitSector1 = false;
            let hitSector2 = false;
            let isOnFinishLine = false;

            for (let pt of points) {
                let col = Math.floor(pt.x / game.tileSize);
                let row = Math.floor(pt.y / game.tileSize);

                if (row < 0 || row >= currentTrackMap.length || col < 0 || col >= currentTrackMap[0].length) {
                    canMove = false;
                    break;
                }

                let tile = currentTrackMap[row][col];

                if (tile === 0 || tile === 4 || tile === 5) {
                    canMove = false;
                    break;
                }

                if (tile === 6) hitSector1 = true;
                if (tile === 3) hitSector2 = true;
                if (tile === 2) isOnFinishLine = true;
            }

            if (canMove) {
                pState.x = nextX;
                pState.y = nextY;

                if (hitSector1 && pState.progress === 0) pState.progress = 1;
                if (hitSector2 && pState.progress === 1) pState.progress = 2;

                if (isOnFinishLine && pState.progress === 2) {
                    pState.finished = true;
                    pState.progress = 3;

                    const lapTimeMs = Date.now() - game.startTime;
                    pState.time = lapTimeMs;

                    // --- NUOVA LOGICA LEADERBOARD ---
                    const trackName = currentTrackMap === game.tracks[0].map ? game.tracks[0].name : game.tracks[game.currentTrackIndex].name;
                    const isRecord = leaderboard.isTop10Record(trackName, lapTimeMs);

                    // Salviamo il tempo e la FLAG isRecord nel podio!
                    game.podium.push({
                        color: color,
                        time: lapTimeMs,
                        isRecord: isRecord
                    });

                    pState.place = game.podium.length;

                    const mins = Math.floor(lapTimeMs / 60000);
                    const secs = Math.floor((lapTimeMs % 60000) / 1000);
                    const ms = lapTimeMs % 1000;
                    const formatted = `${mins}:${secs.toString().padStart(2, '0')}.${ms.toString().padStart(3, '0')}`;

                    // Se è da Top 10, facciamo esplodere la chat!
                    if (isRecord) {
                        io.to(lobbyId).emit('message', {
                            message: `🚨 TEMPO DA TOP 10! ${color} ha chiuso in ${formatted}! 🚨`,
                            type: 'success'
                        });
                    } else {
                        io.to(lobbyId).emit('message', {
                            message: `🏁 ${color} ha finito la gara in ${formatted}`,
                            type: 'success'
                        });
                    }
                }
            }

            if (dx !== 0 || dy !== 0) {
                let targetAngle = Math.atan2(dy, dx) * (180 / Math.PI);
                let diff = targetAngle - pState.angle;
                while (diff <= -180) diff += 360;
                while (diff > 180) diff -= 360;
                pState.angle += diff;
            }
        }

        io.to(lobbyId).emit('racingStateUpdate', game.playersState);

        // Se tutti hanno finito la gara attuale
        if (everyoneFinished && game.players.length > 0) {
            handleRaceEnd(io, lobbyId);
        }
    }, 1000 / 60);
}

